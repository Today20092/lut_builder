import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('project links and identity are available before and after setup @checks', async ({ page, request }) => {
  await page.goto('./')
  const footer = page.getByRole('contentinfo')
  await expect(footer.getByRole('link', { name: 'About', exact: true })).toHaveAttribute('href', '/lut_builder/docs/about/')
  await expect(footer.getByRole('link', { name: /^GitHub/ })).toHaveAttribute('href', 'https://github.com/Today20092/lut_builder')
  await expect(footer.getByRole('link', { name: /^Support this project/ })).toHaveAttribute('href', 'https://ko-fi.com/ayoubab1')
  await expect(page.locator('meta[name="description"]')).toHaveAttribute('content', /false-color exposure LUTs/)
  const icon = page.locator('link[rel="icon"]')
  await expect(icon).toHaveAttribute('href', '/lut_builder/favicon.svg')
  const response = await request.get((await icon.getAttribute('href'))!)
  expect(response.ok()).toBe(true)
  expect(response.headers()['content-type']).toContain('image/svg+xml')
  await page.getByRole('button', { name: 'Skip setup', exact: true }).click()
  await footer.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).include('.site-footer').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: `test-results/footer-${test.info().project.name}.png` })
})

test('selected band removal is grouped, confirmed, cancellable and undoable @checks', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Skip setup', exact: true }).click()
  const table = page.getByRole('table', { name: 'Band colors and positions' })
  const count = await table.locator('tbody tr').count()
  const remove = page.getByRole('button', { name: 'Remove band 1', exact: true })
  const actions = page.viewportSize()!.width < 960 ? page.locator('.workspace-mobile-band-actions') : page.locator('.workspace-band-actions')
  await expect(actions.getByRole('button', { name: 'Remove band 1', exact: true })).toBeVisible()
  await expect(actions.getByRole('button', { name: 'Add band', exact: true })).toBeVisible()
  await remove.click()
  const dialog = page.getByRole('dialog', { name: 'Remove band 1?', exact: true })
  await expect(dialog).toBeVisible()
  await expect(table.locator('tbody tr')).toHaveCount(count)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: `test-results/remove-band-${test.info().project.name}.png` })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(remove).toBeFocused()
  await expect(table.locator('tbody tr')).toHaveCount(count)
  await remove.click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(remove).toBeFocused()
  await remove.click()
  await page.goBack()
  await expect(dialog).not.toBeVisible()
  await expect(remove).toBeFocused()
  await remove.click()
  await dialog.getByRole('button', { name: 'Confirm remove band 1', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(count - 1)
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Undo last band edit', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(count)
  // The graph shortcut reaches the same confirmation without editing immediately.
  const handle = page.getByRole('button', { name: /^Band 1, .* stops$/ }).first()
  await handle.focus()
  await handle.press('Delete')
  await expect(dialog).toBeVisible()
  await expect(table.locator('tbody tr')).toHaveCount(count)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
})
